"""Prepare the 84 Windows build stages from the exact FFmpeg-Builds CI cache."""
import argparse
import concurrent.futures
import hashlib
import json
from pathlib import Path, PurePosixPath
import re
import shutil
import tarfile
import zipfile

ROOT = Path(__file__).resolve().parents[1]
CI_SHA = '6260d7ed7f4df686bc1eb9597cbb07afcd685628735966c8f1ddff60ac2ce24a'
RECIPE = 'c9fe5114060e507409f7ee07edfd82efaf25d767'
FFMPEG = 'a35157abb96167fd7308edc92b55408d5bb084b0'
LICENSE = re.compile(r'^(?:.*[-_ ])?(?:licen[cs]es?|copying|copyright|third[-_ ]?party[-_ ]notices?|notices?|authors|patents|unlicense)(?:$|[-_. ])', re.I)
IGNORED_EXT = {'.c', '.cpp', '.rs', '.h', '.py', '.js', '.go', '.json', '.png', '.jpg', '.in', '.xml', '.toml', '.pm', '.cc', '.lock', '.svg'}


def digest(p):
    with p.open('rb') as f:
        return hashlib.file_digest(f, 'sha256').hexdigest()


def extract_cache(cache, dockerfile, dest):
    expected = set(re.findall(r'\.cache/downloads/([^,\s]+\.tar\.xz)', dockerfile.read_text()))
    if len(expected) != 84:
        raise ValueError(f'Expected the pinned Dockerfile with 84 build cache mounts, found {len(expected)}')
    if digest(cache) != CI_SHA:
        raise ValueError('Wrong upstream CI artifact')
    dest.mkdir(parents=True, exist_ok=True)
    found = set()
    with zipfile.ZipFile(cache) as z, z.open('cache.tar.gz') as compressed, tarfile.open(fileobj=compressed, mode='r|gz') as tar:
        for m in tar:
            name = PurePosixPath(m.name).name
            if m.isfile() and name in expected:
                if name in found:
                    raise ValueError('Duplicate build cache entry '+name)
                with (dest/name).open('wb') as f:
                    shutil.copyfileobj(tar.extractfile(m), f, 1024*1024)
                found.add(name)
    if expected != found:
        raise ValueError('Missing build stages '+str(expected-found))
    return [dest/name for name in sorted(found)]


def read_notices(archive):
    licenses = {}
    config_count = 0
    with tarfile.open(archive, mode='r|*') as tar:
        for m in tar:
            if not m.isfile():
                continue
            p = PurePosixPath(m.name)
            if '.git' in p.parts:
                if p.name == 'config':
                    body = tar.extractfile(m).read()
                    if re.search(rb'http\S*://[^/\s]+:[^/\s]+@|extraheader\s*=|authorization:\s*(?:basic|bearer)', body, re.I):
                        raise ValueError('Unexpected credential in upstream stage '+archive.name)
                    config_count += 1
                continue
            if not LICENSE.match(p.name) or p.suffix.lower() in IGNORED_EXT:
                continue
            if p.is_absolute() or '..' in p.parts:
                raise ValueError('Unsafe upstream notice path')
            if m.size > 5*1024*1024:
                raise ValueError('Unexpected notice size: '+str(p))
            raw = tar.extractfile(m).read()
            if b'\0' not in raw[:512]:
                licenses[str(p)] = raw
    return licenses, config_count


def stage_data(path):
    licenses, configs = read_notices(path)
    return path, licenses, dict(stage=path.name.rsplit('_', 1)[0], source=path.name, bytes=path.stat().st_size,
                                sha256=digest(path), notices=len(licenses), git_configurations_checked=configs)


def put(z, name, data):
    info = zipfile.ZipInfo(name)
    info.compress_type = zipfile.ZIP_DEFLATED
    z.writestr(info, data)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('cache', type=Path, help='GitHub Actions artifact 13762902626 ZIP')
    parser.add_argument('dockerfile', type=Path, help='Dockerfile generated by ./generate.sh win64 lgpl-shared 8.1 in pinned recipe')
    parser.add_argument('--out', type=Path, default=ROOT/'artifacts/third-party-cache')
    args = parser.parse_args()
    dest = args.out/'ffmpeg-stages'
    stages = extract_cache(args.cache, args.dockerfile, dest)
    print(f'Extracted {len(stages)} exact stage archives ({sum(p.stat().st_size for p in stages):,} bytes)', flush=True)
    records = []
    with zipfile.ZipFile(args.out/'ffmpeg-notices.zip', 'w') as notices, concurrent.futures.ThreadPoolExecutor(6) as pool:
        for p, files, record in pool.map(stage_data, stages):
            records.append(record)
            for name, data in sorted(files.items()):
                put(notices, record['stage']+'/'+name, data)
            print(record['stage'], record['notices'], flush=True)
        index = json.dumps(records, indent=2).encode()
        put(notices, 'build-stages.json', index)
        (args.out/'ffmpeg-build-stages.json').write_bytes(index)


if __name__ == '__main__':
    main()
